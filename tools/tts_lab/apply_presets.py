#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Merge tools/tts_lab/preset_map.json into KOTONOHA_PRESET_AUDIO.

Idempotent: the auto-generated section is rebuilt from scratch on every run, so
re-baking with a different voice just replaces it. Hand-written entries above
the marker are kept; `--override` lets generated clips win on the same key.

  python tools/tts_lab/apply_presets.py --dry-run
  python tools/tts_lab/apply_presets.py --override
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ENGINE = ROOT / "kotonoha_engine.js"
MAP_FILE = HERE / "preset_map.json"

MARKER = "// ---- auto-generated by tools/tts_lab/batch_tts.py ----"
BLOCK_RE = re.compile(r"(const KOTONOHA_PRESET_AUDIO = \{)(.*?)(\n\};)", re.S)
KEY_RE = re.compile(r'"((?:[^"\\]|\\.)*)"\s*:')


def main(argv=None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--override", action="store_true",
                    help="let generated clips replace hand-written entries with the same text")
    args = ap.parse_args(argv)

    if not MAP_FILE.exists():
        print(f"missing {MAP_FILE} — run batch_tts.py first")
        return 1

    mapping = json.loads(MAP_FILE.read_text(encoding="utf-8"))["map"]
    src = ENGINE.read_text(encoding="utf-8")
    m = BLOCK_RE.search(src)
    if not m:
        print("KOTONOHA_PRESET_AUDIO block not found")
        return 1

    body = m.group(2)
    hand = body.split(MARKER)[0]
    hand_keys = set(KEY_RE.findall(hand))

    kept = [(k, v) for k, v in sorted(mapping.items()) if args.override or k not in hand_keys]
    print(f"hand-written: {len(hand_keys)} · generated: {len(mapping)} · writing: {len(kept)}")
    if not kept:
        print("nothing to do")
        return 0

    lines = [f'  "{k.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}": "{v}",'
             for k, v in kept]

    hand_clean = hand.rstrip().rstrip(",")
    new_body = hand_clean + ",\n  " + MARKER + "\n" + "\n".join(lines)
    out = src[: m.start(2)] + new_body + src[m.end(2):]

    if args.dry_run:
        print("\n".join(lines[:8]))
        print(f"... +{max(0, len(lines) - 8)} more")
        return 0

    ENGINE.write_text(out, encoding="utf-8")
    print(f"patched {ENGINE.name} (+{len(kept)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
